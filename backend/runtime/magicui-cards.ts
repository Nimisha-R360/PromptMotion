const listField = (s: Content) => (s.bullets?.length ? "bullets" : s.items?.length ? "items.heading" : s.stats?.length ? "stats.label" : "title");

export const magicCardMode = (id: MagicCardId): Mode => CARDS[magicSlug(id)].mode;
export function magicCardField(id: MagicCardId, s: Content): string | null {
  const f = CARDS[magicSlug(id)].field;
  if (f === LIST) return listField(s);
  if (f === BODY) return s.body ? "body" : listField(s);
  return f;
}
