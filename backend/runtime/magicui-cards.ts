export type MagicCardId = (typeof MAGICUI_CARD_IDS)[number];
export const isMagicCardId = (v: unknown): v is MagicCardId => typeof v === "string" && (MAGICUI_CARD_IDS as readonly string[]).includes(v);
/** "magicui.card.marquee" → "marquee" (the file in components/magicui) */
export const magicSlug = (id: MagicCardId) => id.slice("magicui.card.".length);

